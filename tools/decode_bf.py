#!/usr/bin/env python3
"""Decrypt a SIGMA BF firmware package without a key.

You must supply the firmware file yourself. No firmware bytes are included in
this repository.

The package uses a byte-wise additive stream (subtract modulo 256), not a
block cipher. The stream is not stored; it is generated by the fixed linear
recurrence over GF(2)^8

    K[i] = K[i-8]  ^ K[i-9]  ^ K[i-12] ^ K[i-13] ^ K[i-15]
           ^ K[i-21] ^ K[i-22] ^ K[i-24] ^ K[i-25] ^ K[i-32]

for i >= 32. The first 32 stream bytes are recovered from the fixed plaintext
at the start of segment 2:

    "MILBEAUT" + 00 00 00 00 00 50 01 00 + mov x0..x3, xzr

so K[0:32] = (segment2_cipher[0:32] - known_plain[0:32]) mod 256. No secret key
is involved.

Because the recurrence is linear over GF(2), it has the doubling property

    K[i] = XOR over t in TAPS of K[i - t * 2^m]

which lets the stream be extended in large blocks instead of one byte at a
time.

The same stream (restarting at offset 0) is subtracted from every segment.

For reference, the vendor parser implements the same stream as a xorshift32
whose seed is stored unencrypted at offset 12 of the package (zero means 1):

    x ^= x << 13; x ^= x >> 17; x ^= x << 15;   // 32-bit
    K[i] = x & 0xFF

and resets the seed for each segment. The tool cross-checks the two prefixes.
This is why no secret and no known plaintext are strictly needed: the header
seed alone reproduces the stream. The recurrence path is kept because it is
independent of the header field and self-verifies against MILBEAUT.

Usage:
    python tools/decode_bf.py BF__V104.bin -o decoded-V104
    python tools/decode_bf.py BF__V104.bin --verify-only
"""

from __future__ import annotations

import argparse
import hashlib
import struct
import sys
from pathlib import Path

TAPS = (8, 9, 12, 13, 15, 21, 22, 24, 25, 32)

# Fixed plaintext at the start of segment 2 (identical in V103 and V104).
KNOWN_32 = bytes.fromhex(
    "4d494c4245415554"          # "MILBEAUT"
    "0000000000500100"          # 0, 0x00015000
    "e0031faae1031faae2031faae3031faa"  # mov x0..x3, xzr
)

MAGIC = b"SIGMA bf SOF"
TABLE_OFF = 0x100
ENTRY = struct.Struct("<HHIII")


def parse_package(data: bytes) -> list[dict]:
    if data[:12] != MAGIC:
        raise ValueError(
            "not a SIGMA BF package (expected %r at offset 0, got %r)"
            % (MAGIC, data[:12])
        )
    count = struct.unpack_from("<H", data, 24)[0]
    if not (1 <= count <= 64):
        raise ValueError("implausible segment count: %d" % count)

    segments = []
    last = 0x300
    for i in range(count):
        index, kind, off, size, trailer = ENTRY.unpack_from(data, TABLE_OFF + 16 * i)
        if index != i:
            raise ValueError("segment table index %d != %d" % (index, i))
        if off < last or off + size > len(data):
            raise ValueError("segment %d out of range" % i)
        payload = data[off:off + size]
        if trailer & 0xFFFFFF:
            raise ValueError("segment %d trailer low bits set" % i)
        if (sum(payload) + (trailer >> 24)) & 0xFF:
            raise ValueError("segment %d checksum mismatch" % i)
        segments.append(
            {"index": i, "kind": kind, "offset": off, "size": size, "cipher": payload}
        )
        last = off + size
    return segments


def xor_bytes(a: bytes, b: bytes) -> bytes:
    n = len(a)
    return (int.from_bytes(a, "little") ^ int.from_bytes(b, "little")).to_bytes(n, "little")


def extend_stream(prefix: bytes, length: int) -> bytearray:
    """Extend the 32-byte prefix to `length` with the doubling recurrence."""
    if len(prefix) != 32:
        raise ValueError("prefix must be 32 bytes")
    if length < 32:
        raise ValueError("length must be >= 32")

    key = bytearray(length)
    key[:32] = prefix
    pos = 32
    while pos < length:
        scale = 1 << ((pos // 32).bit_length() - 1)
        count = min(8 * scale, length - pos)
        block = bytes(count)  # zeros
        for tap in TAPS:
            off = pos - tap * scale
            if off < 0:
                raise ValueError("recurrence underflow at pos=%d" % pos)
            block = xor_bytes(block, key[off:off + count])
        key[pos:pos + count] = block
        pos += count
    return key


def recover_prefix(seg2_cipher: bytes) -> bytes:
    if len(seg2_cipher) < 32:
        raise ValueError("segment 2 is too short")
    return bytes((c - p) & 0xFF for c, p in zip(seg2_cipher[:32], KNOWN_32))


def vendor_prefix(seed: int, length: int = 32) -> bytes:
    """First stream bytes from the xorshift32 seed stored at offset 12."""
    x = seed or 1
    out = bytearray(length)
    for i in range(length):
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 15) & 0xFFFFFFFF
        x &= 0xFFFFFFFF
        out[i] = x & 0xFF
    return bytes(out)


def decrypt_segment(cipher: bytes, key: bytearray) -> bytes:
    if len(cipher) > len(key):
        raise ValueError("stream is shorter than segment")
    out = bytearray(len(cipher))
    # Process in blocks to keep the big-int conversion bounded.
    step = 1 << 20
    for i in range(0, len(cipher), step):
        chunk = cipher[i:i + step]
        out[i:i + len(chunk)] = bytes(
            (c - k) & 0xFF for c, k in zip(chunk, key[i:i + len(chunk)])
        )
    return bytes(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("firmware", help="BF firmware .bin you obtained yourself")
    ap.add_argument("-o", "--out", help="output directory (default: decoded)")
    ap.add_argument("--verify-only", action="store_true",
                    help="decrypt in memory and print checks, write nothing")
    args = ap.parse_args()

    raw = Path(args.firmware).read_bytes()
    print("input : %s" % args.firmware)
    print("sha256: %s" % hashlib.sha256(raw).hexdigest())

    segments = parse_package(raw)
    print("segments: %d" % len(segments))

    seg2 = next((s for s in segments if s["index"] == 2), None)
    if seg2 is None:
        raise SystemExit("segment 2 not present; cannot recover the stream")

    prefix = recover_prefix(seg2["cipher"])
    longest = max(s["size"] for s in segments)
    key = extend_stream(prefix, longest)
    print("stream prefix: %s" % prefix.hex())

    seed = struct.unpack_from("<I", raw, 12)[0]
    if seed:
        check = vendor_prefix(seed)
        print("header seed  : 0x%08x" % seed)
        print("seed prefix  : %s (%s)" % (check.hex(),
                                           "matches" if check == prefix else "DIFFERS"))

    plain = {}
    for s in segments:
        plain[s["index"]] = decrypt_segment(s["cipher"], key)

    # Independent fixed-header checks.
    checks = []
    if plain[2][:8] == b"MILBEAUT":
        checks.append("segment 2 starts with MILBEAUT")
    if 8 in plain and plain[8][:8] == b"Logo\x01\x00\x00\x00":
        checks.append("segment 8 starts with Logo")
    if 0 in plain and plain[0][:8] == b"0x000100":
        checks.append("segment 0 starts with 0x000100")
    for c in checks:
        print("check : %s" % c)
    if plain[2][:8] != b"MILBEAUT":
        print("error : segment 2 does not decrypt to MILBEAUT")
        return 1

    if args.verify_only:
        print("verify-only: ok")
        return 0

    out = Path(args.out or "decoded")
    out.mkdir(parents=True, exist_ok=True)
    for s in segments:
        name = "%02d_%04x.bin" % (s["index"], s["kind"])
        (out / name).write_bytes(plain[s["index"]])
        digest = hashlib.sha256(plain[s["index"]]).hexdigest()
        print("wrote  : %-12s %8d bytes  %s" % (name, s["size"], digest[:16]))
    print("done   : %s" % out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
